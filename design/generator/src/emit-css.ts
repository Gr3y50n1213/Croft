// CSS output: custom properties for every token, one block per preset, mode and contrast.

import { ROLES, CONTRASTS, MODES, presetsOf } from './schemes.ts';
import type { SchemeEntry, StatusEntry } from './schemes.ts';
import { kebab } from './tokens.ts';
import type { Leaf, LeafValue, Tokens } from './tokens.ts';
import { MPL_HEADER_CSS } from './header.ts';
import { springLinearEasing } from './spring.ts';

/** Unit for a token, taken from the nearest key suffix. Dp is a CSS px. */
const UNIT_SUFFIXES: [string, string][] = [['Dp', 'px'], ['Seconds', 's'], ['Ms', 'ms'], ['Deg', 'deg']];

export function cssUnit(path: string[]): string {
  for (let i = path.length - 1; i >= 0; i--) {
    const segment = path[i] as string;
    for (const [suffix, unit] of UNIT_SUFFIXES) {
      if (segment.length > suffix.length && segment.endsWith(suffix)) return unit;
    }
  }
  return '';
}

export function cssName(path: string[]): string {
  return `--croft-${path.map(kebab).join('-')}`;
}

function cssScalar(v: number | string | boolean, unit: string): string {
  return typeof v === 'number' ? `${v}${unit}` : String(v);
}

export function cssValue(value: LeafValue, path: string[]): string {
  const unit = cssUnit(path);
  return Array.isArray(value) ? value.map((v) => cssScalar(v, unit)).join(', ') : cssScalar(value, unit);
}

export function cssModeId(mode: string): string {
  return kebab(mode);
}

export function emitCss(tokens: Tokens, leaves: Leaf[], schemes: SchemeEntry[], status: StatusEntry[]): string {
  const presets = presetsOf(tokens);
  const out: string[] = [];
  const push = (...lines: string[]) => out.push(...lines);

  push(MPL_HEADER_CSS, '');
  push('/* GENERATED by design/generator from design/tokens.json. Do not edit; run `npm run generate`.');
  push(' *');
  push(' * Pick a look with attributes on <html>:');
  push(' *   data-croft-theme="moss|wax|..."  data-croft-mode="light|dark|pure-black"');
  push(' *   data-croft-contrast="standard|medium|high"   (optional; standard is the default)');
  push(' * Lengths are CSS px; one dp is one px. */', '');

  push(':root {');
  for (const [name, hex] of Object.entries(tokens.brand)) push(`  ${cssName(['brand', name])}: ${hex};`);
  for (const leaf of leaves) push(`  ${cssName(leaf.path)}: ${cssValue(leaf.value, leaf.path)};`);

  // Springs as linear() easings, for the web (CSS has no spring easing).
  const springGroups = new Map<string, { stiffness?: number; damping?: number }>();
  for (const leaf of leaves) {
    if (leaf.path[0] !== 'motion') continue;
    const last = leaf.path[leaf.path.length - 1];
    if (last !== 'stiffness' && last !== 'damping') continue;
    const key = leaf.path.slice(0, -1).join('\u0000');
    const entry = springGroups.get(key) ?? {};
    entry[last] = leaf.value as number;
    springGroups.set(key, entry);
  }
  for (const [key, spring] of springGroups) {
    if (spring.stiffness === undefined || spring.damping === undefined) continue;
    const base = key.split('\u0000');
    const { duration, easing } = springLinearEasing(spring.stiffness, spring.damping);
    push(`  ${cssName([...base, 'easing'])}: ${easing};`);
    push(`  ${cssName([...base, 'easing-duration'])}: ${duration}s;`);
  }
  push('}', '');

  for (const preset of presets) {
    for (const mode of MODES) {
      for (const contrast of CONTRASTS) {
        const entry = schemes.find((s) => s.preset === preset.id && s.mode === mode && s.contrast === contrast.id);
        if (!entry) throw new Error(`missing scheme ${preset.id}/${mode}/${contrast.id}`);
        let selector = `[data-croft-theme="${preset.id}"][data-croft-mode="${cssModeId(mode)}"]`;
        if (contrast.id !== 'standard') selector += `[data-croft-contrast="${contrast.id}"]`;
        // The default preset in light mode at standard contrast also answers for a bare <html>.
        if (preset.id === tokens.palettes.default && mode === 'light' && contrast.id === 'standard') {
          selector = `:root,\n${selector}`;
        }
        push(`/* ${preset.id}, ${mode}, ${contrast.id} contrast */`);
        push(`${selector} {`);
        push(`  color-scheme: ${mode === 'light' ? 'light' : 'dark'};`);
        for (const role of ROLES) push(`  ${cssName(['color', role])}: ${entry.colors[role]};`);
        for (const st of status.filter((x) => x.mode === mode && x.contrast === contrast.id)) {
          push(`  ${cssName(['status', st.name])}: ${st.colors.color};`);
          push(`  ${cssName(['status', st.name, 'container'])}: ${st.colors.container};`);
          push(`  ${cssName(['status', st.name, 'on-container'])}: ${st.colors.onContainer};`);
        }
        push('}', '');
      }
    }
  }
  return out.join('\n');
}
