// Kotlin output: Compose colour schemes, token constants and MotionScheme wrappers.

import { ROLES, MODES, CONTRASTS, presetsOf, statusNames } from './schemes.ts';
import type { Role, SchemeEntry, StatusEntry } from './schemes.ts';
import { pascal, upperSnake } from './tokens.ts';
import type { Tokens } from './tokens.ts';
import { MPL_HEADER_SLASH } from './header.ts';

export const KOTLIN_PACKAGE = 'com.example.croft.design';

const KOTLIN_KEYWORDS = new Set([
  'as', 'break', 'class', 'continue', 'do', 'else', 'false', 'for', 'fun', 'if', 'in', 'interface', 'is',
  'null', 'object', 'package', 'return', 'super', 'this', 'throw', 'true', 'try', 'typealias', 'typeof',
  'val', 'var', 'when', 'while',
]);

function ktName(key: string): string {
  return KOTLIN_KEYWORDS.has(key) ? `\`${key}\`` : key;
}

function ktScalar(v: number | string | boolean): string {
  return typeof v === 'string' ? JSON.stringify(v).replace(/\$/g, '\\$') : String(v);
}

function ktValue(v: unknown): string {
  if (Array.isArray(v)) return `listOf(${v.map((x) => ktScalar(x as number | string | boolean)).join(', ')})`;
  return ktScalar(v as number | string | boolean);
}

function ktTree(tree: Record<string, unknown>, depth: number): string[] {
  const pad = '    '.repeat(depth);
  const lines: string[] = [];
  for (const [key, value] of Object.entries(tree)) {
    if (typeof value === 'object' && value !== null && !Array.isArray(value)) {
      lines.push(`${pad}object ${pascal(key)} {`);
      lines.push(...ktTree(value as Record<string, unknown>, depth + 1));
      lines.push(`${pad}}`);
    } else if (Array.isArray(value)) {
      lines.push(`${pad}val ${ktName(key)} = ${ktValue(value)}`);
    } else {
      lines.push(`${pad}const val ${ktName(key)} = ${ktValue(value)}`);
    }
  }
  return lines;
}

function ktColor(hex: string): string {
  return `0xFF${hex.slice(1)}`;
}

const SIZES = ['fast', 'default', 'slow'] as const;

function springRef(path: string[], leaf: 'stiffness' | 'damping'): string {
  return `CroftTokens.${path.map(pascal).join('.')}.${leaf}.toFloat()`;
}

export function emitKotlin(
  tokens: Tokens,
  generic: Record<string, unknown>,
  schemes: SchemeEntry[],
  status: StatusEntry[],
): string {
  const presets = presetsOf(tokens);
  const out: string[] = [];
  const push = (...lines: string[]) => out.push(...lines);

  push(MPL_HEADER_SLASH, '');
  push('// GENERATED by design/generator from design/tokens.json. Do not edit; run `npm run generate`.');
  push('// Written against Compose Material 3 1.5.x: MotionScheme is public there (it is internal in 1.4.0).', '');
  push(`package ${KOTLIN_PACKAGE}`, '');
  push(
    'import androidx.compose.animation.core.FiniteAnimationSpec',
    'import androidx.compose.animation.core.spring',
    'import androidx.compose.material3.ColorScheme',
    'import androidx.compose.material3.MotionScheme',
    'import androidx.compose.material3.darkColorScheme',
    'import androidx.compose.material3.lightColorScheme',
    'import androidx.compose.ui.graphics.Color',
    '',
  );

  // Enums
  push('/** Croft palette presets (docs/ux/theme.md). `seed` is an opaque ARGB value. */');
  push('enum class CroftPreset(val id: String, val seed: Long, val style: String) {');
  presets.forEach((p, i) => {
    push(`    ${upperSnake(p.id)}("${p.id}", ${ktColor(p.seed)}, "${p.style}")${i === presets.length - 1 ? ';' : ','}`);
  });
  push('', '    companion object {', `        val DEFAULT = ${upperSnake(tokens.palettes.default)}`, '    }', '}', '');
  push('enum class CroftMode { ' + MODES.map(upperSnake).join(', ') + ' }', '');
  push('enum class CroftContrast(val level: Float) {');
  CONTRASTS.forEach((c, i) => {
    push(`    ${upperSnake(c.id)}(${c.level}f)${i === CONTRASTS.length - 1 ? ';' : ','}`);
  });
  push('}', '');

  // Roles
  push('/** One colour per Material 3 role, as opaque ARGB values (0xFFRRGGBB). */');
  push('data class CroftColorRoles(');
  for (const role of ROLES) push(`    val ${role}: Long,`);
  push(')', '');

  // Generic tokens
  push('/** Everything in tokens.json except colours. Whole numbers are Int, others Double. */');
  push('object CroftTokens {');
  push(...ktTree(generic, 1));
  push('}', '');

  // Brand
  push('/** Brand colours from tokens.json. Use the theme roles in UI; these are for brand surfaces only. */');
  push('object CroftBrand {');
  for (const [name, hex] of Object.entries(tokens.brand)) {
    push(`    val ${ktName(name)} = Color(${ktColor(hex)})`);
  }
  push('}', '');

  // Schemes
  push('data class CroftSchemeKey(val preset: CroftPreset, val mode: CroftMode, val contrast: CroftContrast)', '');
  push('/** Precomputed Material Color Utilities (HCT) schemes: every preset in every mode at every contrast. */');
  push('object CroftSchemes {');
  for (const p of presets) {
    push(`    private val ${p.id} = mapOf(`);
    for (const entry of schemes.filter((s) => s.preset === p.id)) {
      push(
        `        CroftSchemeKey(CroftPreset.${upperSnake(p.id)}, CroftMode.${upperSnake(entry.mode)}, CroftContrast.${upperSnake(entry.contrast)}) to CroftColorRoles(`,
      );
      for (const role of ROLES) push(`            ${role} = ${ktColor(entry.colors[role as Role])},`);
      push('        ),');
    }
    push('    )', '');
  }
  push(`    val all: Map<CroftSchemeKey, CroftColorRoles> =`);
  push('        ' + presets.map((p) => p.id).join(' + '));
  push('');
  push('    fun roles(preset: CroftPreset, mode: CroftMode, contrast: CroftContrast = CroftContrast.STANDARD): CroftColorRoles =');
  push('        all.getValue(CroftSchemeKey(preset, mode, contrast))');
  push('}', '');

  // Status colours
  push('/** One status colour at one mode and contrast: the colour (icons), a container fill and the text on it. */');
  push('data class CroftStatusRoles(val color: Long, val container: Long, val onContainer: Long)', '');
  push('data class CroftStatusKey(val mode: CroftMode, val contrast: CroftContrast)', '');
  push('/** Status colours from tokens.json (a fixed HCT hue and chroma at set tones). Pure black uses the dark tones. */');
  push('object CroftStatus {');
  for (const name of statusNames(status)) {
    push(`    private val ${name}Table = mapOf(`);
    for (const e of status.filter((x) => x.name === name)) {
      push(
        `        CroftStatusKey(CroftMode.${upperSnake(e.mode)}, CroftContrast.${upperSnake(e.contrast)}) to CroftStatusRoles(${ktColor(e.colors.color)}, ${ktColor(e.colors.container)}, ${ktColor(e.colors.onContainer)}),`,
      );
    }
    push('    )', '');
    push(`    fun ${name}(mode: CroftMode, contrast: CroftContrast = CroftContrast.STANDARD): CroftStatusRoles =`);
    push(`        ${name}Table.getValue(CroftStatusKey(mode, contrast))`);
  }
  push('}', '');

  // Compose builders
  for (const kind of ['light', 'dark'] as const) {
    push(`private fun CroftColorRoles.to${pascal(kind)}ColorScheme(): ColorScheme =`);
    push(`    ${kind}ColorScheme(`);
    for (const role of ROLES) push(`        ${role} = Color(${role}),`);
    push('    )', '');
  }
  push('/** Compose colour scheme for a role set. Pure black is a dark scheme with black base surfaces. */');
  push('fun CroftColorRoles.toColorScheme(mode: CroftMode): ColorScheme =');
  push('    if (mode == CroftMode.LIGHT) toLightColorScheme() else toDarkColorScheme()', '');
  push('fun croftColorScheme(');
  push('    preset: CroftPreset = CroftPreset.DEFAULT,');
  push('    mode: CroftMode = CroftMode.LIGHT,');
  push('    contrast: CroftContrast = CroftContrast.STANDARD,');
  push('): ColorScheme = CroftSchemes.roles(preset, mode, contrast).toColorScheme(mode)', '');

  // Motion
  const spatial = ['motion', 'spatial'];
  const effects = ['motion', 'effects'];
  const reduced = ['motion', 'standardSpatialForReducedMotion'];
  push('/** A spring from tokens.json: stiffness and damping ratio, as Compose `spring` takes them. */');
  push('class CroftSpring(val stiffness: Float, val dampingRatio: Float) {');
  push('    fun <T> spec(): FiniteAnimationSpec<T> = spring(dampingRatio = dampingRatio, stiffness = stiffness)');
  push('}', '');
  push('object CroftMotion {');
  for (const [prefix, group] of [['spatial', spatial], ['effects', effects], ['reducedSpatial', reduced]] as const) {
    for (const size of SIZES) {
      const path = [...group, size];
      push(`    val ${prefix}${pascal(size)} = CroftSpring(${springRef(path, 'stiffness')}, ${springRef(path, 'damping')})`);
    }
  }
  push('}', '');
  push('private class CroftMotionScheme(reducedMotion: Boolean) : MotionScheme {');
  push('    private val spatialFast = if (reducedMotion) CroftMotion.reducedSpatialFast else CroftMotion.spatialFast');
  push('    private val spatialDefault = if (reducedMotion) CroftMotion.reducedSpatialDefault else CroftMotion.spatialDefault');
  push('    private val spatialSlow = if (reducedMotion) CroftMotion.reducedSpatialSlow else CroftMotion.spatialSlow');
  push('');
  push('    override fun <T> defaultSpatialSpec(): FiniteAnimationSpec<T> = spatialDefault.spec()');
  push('    override fun <T> fastSpatialSpec(): FiniteAnimationSpec<T> = spatialFast.spec()');
  push('    override fun <T> slowSpatialSpec(): FiniteAnimationSpec<T> = spatialSlow.spec()');
  push('    override fun <T> defaultEffectsSpec(): FiniteAnimationSpec<T> = CroftMotion.effectsDefault.spec()');
  push('    override fun <T> fastEffectsSpec(): FiniteAnimationSpec<T> = CroftMotion.effectsFast.spec()');
  push('    override fun <T> slowEffectsSpec(): FiniteAnimationSpec<T> = CroftMotion.effectsSlow.spec()');
  push('}', '');
  push('private val CroftExpressiveMotionScheme: MotionScheme = CroftMotionScheme(reducedMotion = false)');
  push('private val CroftReducedMotionScheme: MotionScheme = CroftMotionScheme(reducedMotion = true)', '');
  push('/** Pass to `MaterialTheme(motionScheme = ...)`. Reduced swaps in the standard spatial springs (docs/ux/motion.md). */');
  push('fun croftMotionScheme(reducedMotion: Boolean = false): MotionScheme =');
  push('    if (reducedMotion) CroftReducedMotionScheme else CroftExpressiveMotionScheme');
  push('');

  return out.join('\n');
}
