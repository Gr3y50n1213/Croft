// Swift output: SwiftUI colours from hex, token constants and spring animations.

import { ROLES, MODES, CONTRASTS, presetsOf } from './schemes.ts';
import type { SchemeEntry, StatusEntry } from './schemes.ts';
import { pascal } from './tokens.ts';
import type { Tokens } from './tokens.ts';
import { MPL_HEADER_SLASH } from './header.ts';

const SWIFT_KEYWORDS = new Set([
  'associatedtype', 'class', 'deinit', 'enum', 'extension', 'fileprivate', 'func', 'import', 'init', 'inout',
  'internal', 'let', 'open', 'operator', 'private', 'precedencegroup', 'protocol', 'public', 'rethrows', 'static',
  'struct', 'subscript', 'typealias', 'var', 'break', 'case', 'catch', 'continue', 'default', 'defer', 'do', 'else',
  'fallthrough', 'for', 'guard', 'if', 'in', 'repeat', 'return', 'throw', 'switch', 'where', 'while', 'as', 'false',
  'is', 'nil', 'self', 'super', 'throws', 'true', 'try',
]);

function swName(key: string): string {
  return SWIFT_KEYWORDS.has(key) ? `\`${key}\`` : key;
}

function swScalar(v: number | string | boolean): string {
  return typeof v === 'string' ? JSON.stringify(v) : String(v);
}

function swType(v: unknown): string {
  if (Array.isArray(v)) return `[${swType(v[0])}]`;
  if (typeof v === 'number') return Number.isInteger(v) ? 'Int' : 'Double';
  if (typeof v === 'boolean') return 'Bool';
  return 'String';
}

function swValue(v: unknown): string {
  if (Array.isArray(v)) return `[${v.map((x) => swScalar(x as number | string | boolean)).join(', ')}]`;
  return swScalar(v as number | string | boolean);
}

function swTree(tree: Record<string, unknown>, depth: number): string[] {
  const pad = '    '.repeat(depth);
  const lines: string[] = [];
  for (const [key, value] of Object.entries(tree)) {
    if (typeof value === 'object' && value !== null && !Array.isArray(value)) {
      lines.push(`${pad}enum ${pascal(key)} {`);
      lines.push(...swTree(value as Record<string, unknown>, depth + 1));
      lines.push(`${pad}}`);
    } else {
      lines.push(`${pad}static let ${swName(key)}: ${swType(value)} = ${swValue(value)}`);
    }
  }
  return lines;
}

function swHex(hex: string): string {
  return `0x${hex.slice(1)}`;
}

const SIZES = ['fast', 'default', 'slow'] as const;

function springArgs(path: string[]): string {
  const ref = `CroftTokens.${path.map(pascal).join('.')}`;
  return `stiffness: Double(${ref}.stiffness), damping: Double(${ref}.damping), response: Double(${ref}.swiftUIResponse)`;
}

export function emitSwift(
  tokens: Tokens,
  generic: Record<string, unknown>,
  schemes: SchemeEntry[],
  status: StatusEntry[],
): string {
  const presets = presetsOf(tokens);
  const out: string[] = [];
  const push = (...lines: string[]) => out.push(...lines);

  push(MPL_HEADER_SLASH, '');
  push('// GENERATED by design/generator from design/tokens.json. Do not edit; run `npm run generate`.', '');
  push('import SwiftUI', '');

  push('/// Croft palette presets (docs/ux/theme.md). `seed` is 0xRRGGBB.');
  push('enum CroftPreset: String, CaseIterable, Hashable {');
  for (const p of presets) push(`    case ${swName(p.id)}`);
  push('', '    var seed: UInt32 {', '        switch self {');
  for (const p of presets) push(`        case .${swName(p.id)}: return ${swHex(p.seed)}`);
  push('        }', '    }', '', '    var style: String {', '        switch self {');
  for (const p of presets) push(`        case .${swName(p.id)}: return "${p.style}"`);
  push('        }', '    }', '', `    static let \`default\` = CroftPreset.${tokens.palettes.default}`, '}', '');
  push('enum CroftMode: String, CaseIterable, Hashable {');
  for (const m of MODES) push(`    case ${m}`);
  push('}', '');
  push('enum CroftContrast: String, CaseIterable, Hashable {');
  for (const c of CONTRASTS) push(`    case ${c.id}`);
  push('', '    var level: Double {', '        switch self {');
  for (const c of CONTRASTS) push(`        case .${c.id}: return ${c.level}`);
  push('        }', '    }', '}', '');

  push('/// One colour per Material 3 role, as 0xRRGGBB values. All roles are opaque.');
  push('struct CroftColorRoles {');
  for (const role of ROLES) push(`    let ${role}: UInt32`);
  push('}', '');

  push('/// The same roles as SwiftUI colours.');
  push('struct CroftColors {');
  for (const role of ROLES) push(`    let ${role}: Color`);
  push('', '    init(_ roles: CroftColorRoles) {');
  for (const role of ROLES) push(`        ${role} = Color(hex: roles.${role})`);
  push('    }', '}', '');
  push('extension Color {');
  push('    /// An opaque sRGB colour from 0xRRGGBB.');
  push('    init(hex: UInt32) {');
  push('        self.init(');
  push('            .sRGB,');
  push('            red: Double((hex >> 16) & 0xFF) / 255.0,');
  push('            green: Double((hex >> 8) & 0xFF) / 255.0,');
  push('            blue: Double(hex & 0xFF) / 255.0,');
  push('            opacity: 1.0');
  push('        )');
  push('    }', '}', '');

  push('/// Everything in tokens.json except colours. Whole numbers are Int, others Double.');
  push('enum CroftTokens {');
  push(...swTree(generic, 1));
  push('}', '');

  push('/// Brand colours from tokens.json. Use the theme roles in UI; these are for brand surfaces only.');
  push('enum CroftBrand {');
  for (const [name, hex] of Object.entries(tokens.brand)) {
    push(`    static let ${swName(name)} = Color(hex: ${swHex(hex)})`);
  }
  push('}', '');

  push('struct CroftSchemeKey: Hashable {');
  push('    let preset: CroftPreset', '    let mode: CroftMode', '    let contrast: CroftContrast');
  push('}', '');
  push('/// Precomputed Material Color Utilities (HCT) schemes: every preset in every mode at every contrast.');
  push('enum CroftSchemes {');
  for (const p of presets) {
    push(`    private static let ${p.id}: [CroftSchemeKey: CroftColorRoles] = [`);
    for (const entry of schemes.filter((s) => s.preset === p.id)) {
      push(`        CroftSchemeKey(preset: .${swName(p.id)}, mode: .${entry.mode}, contrast: .${entry.contrast}): CroftColorRoles(`);
      ROLES.forEach((role, i) => {
        push(`            ${role}: ${swHex(entry.colors[role])}${i === ROLES.length - 1 ? '' : ','}`);
      });
      push('        ),');
    }
    push('    ]', '');
  }
  push('    static let all: [CroftSchemeKey: CroftColorRoles] = {');
  push('        var merged: [CroftSchemeKey: CroftColorRoles] = [:]');
  push(`        for table in [${presets.map((p) => p.id).join(', ')}] {`);
  push('            merged.merge(table) { current, _ in current }');
  push('        }', '        return merged', '    }()', '');
  push('    static func roles(');
  push('        _ preset: CroftPreset,');
  push('        _ mode: CroftMode,');
  push('        _ contrast: CroftContrast = .standard');
  push('    ) -> CroftColorRoles {');
  push('        guard let roles = all[CroftSchemeKey(preset: preset, mode: mode, contrast: contrast)] else {');
  push('            preconditionFailure("CroftSchemes is missing a preset, mode and contrast combination")');
  push('        }', '        return roles', '    }', '');
  push('    static func colors(');
  push('        _ preset: CroftPreset,');
  push('        _ mode: CroftMode,');
  push('        _ contrast: CroftContrast = .standard');
  push('    ) -> CroftColors {');
  push('        CroftColors(roles(preset, mode, contrast))', '    }');
  push('}', '');

  push('struct CroftStatusRoles {', '    let color: UInt32', '    let container: UInt32', '    let onContainer: UInt32', '}', '');
  push('struct CroftStatusKey: Hashable {', '    let mode: CroftMode', '    let contrast: CroftContrast', '}', '');
  push('/// Status colours from tokens.json (a fixed HCT hue and chroma at set tones). Pure black uses the dark tones.');
  push('enum CroftStatus {');
  for (const name of [...new Set(status.map((x) => x.name))]) {
    push(`    private static let ${name}Table: [CroftStatusKey: CroftStatusRoles] = [`);
    for (const e of status.filter((x) => x.name === name)) {
      push(`        CroftStatusKey(mode: .${e.mode}, contrast: .${e.contrast}): CroftStatusRoles(color: ${swHex(e.colors.color)}, container: ${swHex(e.colors.container)}, onContainer: ${swHex(e.colors.onContainer)}),`);
    }
    push('    ]', '');
    push(`    static func ${name}(_ mode: CroftMode, _ contrast: CroftContrast = .standard) -> CroftStatusRoles {`);
    push(`        guard let roles = ${name}Table[CroftStatusKey(mode: mode, contrast: contrast)] else {`);
    push('            preconditionFailure("CroftStatus is missing a mode and contrast combination")');
    push('        }', '        return roles', '    }');
  }
  push('}', '');

  push('/// A spring from tokens.json. SwiftUI takes `response` (2 pi / sqrt(stiffness)) and a damping fraction.');
  push('struct CroftSpring {');
  push('    let stiffness: Double', '    let damping: Double', '    let response: Double', '');
  push('    var animation: Animation {');
  push('        .spring(response: response, dampingFraction: damping)', '    }', '}', '');
  push('enum CroftMotion {');
  for (const [prefix, group] of [
    ['spatial', ['motion', 'spatial']],
    ['effects', ['motion', 'effects']],
    ['reducedSpatial', ['motion', 'standardSpatialForReducedMotion']],
  ] as const) {
    for (const size of SIZES) {
      push(`    static let ${prefix}${pascal(size)} = CroftSpring(${springArgs([...group, size])})`);
    }
  }
  push('}', '');
  return out.join('\n');
}
