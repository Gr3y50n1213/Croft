// TypeScript output: the same values as a module the web app imports.

import { ROLES, CONTRASTS, MODES, presetsOf, statusNames } from './schemes.ts';
import type { SchemeEntry, StatusEntry } from './schemes.ts';
import type { Tokens } from './tokens.ts';
import { MPL_HEADER_SLASH } from './header.ts';
import { springLinearEasing } from './spring.ts';

export function emitTs(tokens: Tokens, generic: Record<string, unknown>, schemes: SchemeEntry[], status: StatusEntry[]): string {
  const presets = presetsOf(tokens);
  const out: string[] = [];
  const push = (...lines: string[]) => out.push(...lines);

  push(MPL_HEADER_SLASH, '');
  push('// GENERATED by design/generator from design/tokens.json. Do not edit; run `npm run generate`.', '');

  push('/** Everything in tokens.json except colours. */');
  push(`export const croftTokens = ${JSON.stringify(generic, null, 2)} as const;`, '');

  push('/** Brand colours from tokens.json. Use the theme roles in UI; these are for brand surfaces only. */');
  push(`export const croftBrand = ${JSON.stringify(tokens.brand, null, 2)} as const;`, '');

  push('export const croftPresets = {');
  for (const p of presets) push(`  ${p.id}: { seed: '${p.seed}', style: '${p.style}' },`);
  push('} as const;', '');
  push(`export const croftDefaultPreset = '${tokens.palettes.default}' as const;`, '');
  push(`export const croftModes = ${JSON.stringify(MODES)} as const;`);
  push(`export const croftContrastLevels = {`);
  for (const c of CONTRASTS) push(`  ${c.id}: ${c.level},`);
  push('} as const;', '');
  push('export type CroftPresetId = keyof typeof croftPresets;');
  push('export type CroftMode = (typeof croftModes)[number];');
  push('export type CroftContrast = keyof typeof croftContrastLevels;');
  push(`export type CroftRole = ${ROLES.map((r) => `'${r}'`).join(' | ')};`);
  push('export type CroftColorRoles = Readonly<Record<CroftRole, string>>;', '');

  push('/** Precomputed Material Color Utilities (HCT) schemes as #RRGGBB: preset, then mode, then contrast. */');
  push('export const croftSchemes = {');
  for (const p of presets) {
    push(`  ${p.id}: {`);
    for (const mode of MODES) {
      push(`    ${mode}: {`);
      for (const contrast of CONTRASTS) {
        const entry = schemes.find((s) => s.preset === p.id && s.mode === mode && s.contrast === contrast.id);
        if (!entry) throw new Error(`missing scheme ${p.id}/${mode}/${contrast.id}`);
        push(`      ${contrast.id}: {`);
        for (const role of ROLES) push(`        ${role}: '${entry.colors[role]}',`);
        push('      },');
      }
      push('    },');
    }
    push('  },');
  }
  push('} as const satisfies Record<CroftPresetId, Record<CroftMode, Record<CroftContrast, CroftColorRoles>>>;', '');

  push('export function croftColors(');
  push('  preset: CroftPresetId = croftDefaultPreset,');
  push("  mode: CroftMode = 'light',");
  push("  contrast: CroftContrast = 'standard',");
  push('): CroftColorRoles {');
  push('  return croftSchemes[preset][mode][contrast];', '}', '');

  push('/** Status colours (amber): colour for icons, a container fill and the text on it, per mode then contrast. */');
  push('export const croftStatus = {');
  for (const name of statusNames(status)) {
    push(`  ${name}: {`);
    for (const mode of MODES) {
      push(`    ${mode}: {`);
      for (const contrast of CONTRASTS) {
        const e = status.find((x) => x.name === name && x.mode === mode && x.contrast === contrast.id);
        if (!e) throw new Error(`missing status ${name}/${mode}/${contrast.id}`);
        push(`      ${contrast.id}: { color: '${e.colors.color}', container: '${e.colors.container}', onContainer: '${e.colors.onContainer}' },`);
      }
      push('    },');
    }
    push('  },');
  }
  push('} as const;', '');

  // Spring easings for the web, one per spring token.
  push('/** CSS `linear()` easings that approximate each spring, with the time to settle in seconds. */');
  push('export const croftSpringEasings = {');
  const motion = generic.motion as Record<string, Record<string, { stiffness: number; damping: number }>>;
  for (const [group, sizes] of Object.entries(motion)) {
    for (const [size, spring] of Object.entries(sizes)) {
      const { duration, easing } = springLinearEasing(spring.stiffness, spring.damping);
      push(`  '${group}.${size}': { duration: ${duration}, easing: '${easing}' },`);
    }
  }
  push('} as const;', '');
  return out.join('\n');
}
